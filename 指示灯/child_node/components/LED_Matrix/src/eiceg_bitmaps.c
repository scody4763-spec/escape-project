void shift_pixels_left(uint8_t *bitmap)
{
    for (int i = 0; i < 32; i++) {
        uint8_t data[4] = {
            bitmap[i * 4],
            bitmap[i * 4 + 1],
            bitmap[i * 4 + 2],
            bitmap[i * 4 + 3]
        };

        bitmap[i * 4]     = (data[0] << 1) | ((data[1] & 0x80) ? 1 : 0);
        bitmap[i * 4 + 1] = (data[1] << 1) | ((data[2] & 0x80) ? 1 : 0);
        bitmap[i * 4 + 2] = (data[2] << 1) | ((data[3] & 0x80) ? 1 : 0);
        bitmap[i * 4 + 3] = (data[3] << 1) | ((data[0] & 0x80) ? 1 : 0);
    }
}

void shift_pixels_right(uint8_t *bitmap)
{
    for (int i = 0; i < 32; i++) {
        uint8_t data[4] = {
            bitmap[i * 4],
            bitmap[i * 4 + 1],
            bitmap[i * 4 + 2],
            bitmap[i * 4 + 3]
        };

        bitmap[i * 4]     = (data[0] >> 1) | ((data[3] & 0x01) ? 0x80 : 0);
        bitmap[i * 4 + 1] = (data[1] >> 1) | ((data[0] & 0x01) ? 0x80 : 0);
        bitmap[i * 4 + 2] = (data[2] >> 1) | ((data[1] & 0x01) ? 0x80 : 0);
        bitmap[i * 4 + 3] = (data[3] >> 1) | ((data[2] & 0x01) ? 0x80 : 0);
    }
}

void shift_pixels_up(uint8_t *bitmap)
{
    uint8_t first_row[4];
    memcpy(first_row, bitmap, 4);

    for (int i = 0; i < 31; i++) {
        memcpy(&bitmap[i * 4], &bitmap[(i + 1) * 4], 4);
    }
    memcpy(&bitmap[31 * 4], first_row, 4);
}

void shift_pixels_down(uint8_t *bitmap)
{
    uint8_t last_row[4];
    memcpy(last_row, &bitmap[31 * 4], 4);

    for (int i = 31; i > 0; i--) {
        memcpy(&bitmap[i * 4], &bitmap[(i - 1) * 4], 4);
    }
    memcpy(bitmap, last_row, 4);
}

